"""真实迁移验证：把 SQLite 的一张表实际迁到 PostgreSQL 并跑查询。

不是「看代码推测能不能迁」，而是**真的迁一遍**：
- 建表（类型映射）
- 导数据（含 BLOB / 时间戳 / 大文本）
- 跑现有代码里真实用到的查询
- 对比结果

这样能暴露「看代码看不出来」的问题，比如：
- SQLite 的 TEXT 时间戳在 PG 里排序行为不同
- `INSERT OR REPLACE` 在 PG 里要改成 `ON CONFLICT DO UPDATE`
- 隐式类型转换（SQLite 宽松，PG 严格）

用法：
    python tests/manual/pg_migration_probe.py
"""
from __future__ import annotations

import asyncio
import sqlite3
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(BACKEND))

SQLITE = BACKEND / "data" / "app.db"
PG_DSN = "postgresql://hlz:eval123@127.0.0.1:15432/hlz"

RESULTS: list[tuple[str, bool, str]] = []


def record(name: str, ok: bool, detail: str = "") -> None:
    RESULTS.append((name, ok, detail))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f" — {detail}" if detail else ""))


# 选三张有代表性的表：
#   messages        - 大表、JSON 内容、时间戳
#   team_events     - INTEGER PRIMARY KEY（自增主键，PG 需要 SERIAL/IDENTITY）
#   user_mcp_servers - 含 BLOB 和大文本配置
TABLES = ["messages", "team_events", "user_mcp_servers"]


def sqlite_cols(conn, table: str) -> list[dict]:
    return [dict(r) for r in conn.execute(f"PRAGMA table_info({table})")]


def pg_type(sqlite_type: str, is_pk: bool) -> str:
    t = (sqlite_type or "").upper().split("(")[0].strip()
    if is_pk and t == "INTEGER":
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY"
    return {"TEXT": "TEXT", "INTEGER": "BIGINT", "REAL": "DOUBLE PRECISION",
            "BLOB": "BYTEA", "NUMERIC": "NUMERIC"}.get(t, "TEXT")


async def main() -> int:
    try:
        import asyncpg
    except ImportError:
        print("缺 asyncpg")
        return 2

    if not SQLITE.exists():
        print(f"SQLite 不存在: {SQLITE}")
        return 2

    lite = sqlite3.connect(str(SQLITE))
    lite.row_factory = sqlite3.Row

    try:
        pg = await asyncpg.connect(PG_DSN)
    except Exception as exc:  # noqa: BLE001
        print(f"连不上 PG（{PG_DSN}）：{exc}")
        print("先起容器：docker run -d --name hlz-pg-eval -e POSTGRES_PASSWORD=eval123 "
              "-e POSTGRES_USER=hlz -e POSTGRES_DB=hlz -p 15432:5432 postgres:16-bookworm")
        return 2

    try:
        for table in TABLES:
            print(f"\n===== {table} =====")
            cols = sqlite_cols(lite, table)
            if not cols:
                record(f"{table}: 表存在", False, "SQLite 里没有这张表")
                continue

            # ---- 1. 建表 ----
            await pg.execute(f'DROP TABLE IF EXISTS "{table}"')
            defs = []
            pk = [c for c in cols if c["pk"]]
            for c in cols:
                is_pk = bool(c["pk"])
                typ = pg_type(c["type"], is_pk)
                null = "" if is_pk or c["notnull"] else ""
                d = f'"{c["name"]}" {typ}{null}'
                if is_pk and len(pk) == 1:
                    d += " PRIMARY KEY"
                defs.append(d)
            if len(pk) > 1:
                names = ", ".join(f'"{c["name"]}"' for c in pk)
                defs.append(f"PRIMARY KEY ({names})")
            ddl = f'CREATE TABLE "{table}" ({", ".join(defs)})'
            try:
                await pg.execute(ddl)
                record(f"{table}: 建表成功", True, f"{len(cols)} 列")
            except Exception as exc:  # noqa: BLE001
                record(f"{table}: 建表成功", False, f"{type(exc).__name__}: {exc}")
                continue

            # ---- 2. 导数据 ----
            rows = lite.execute(f"select * from {table}").fetchall()
            if not rows:
                record(f"{table}: 无数据（跳过导入）", True, "0 行")
                continue

            names = [c["name"] for c in cols]
            placeholders = ", ".join(f"${i+1}" for i in range(len(names)))
            collist = ", ".join(f'"{n}"' for n in names)
            insert = f'INSERT INTO "{table}" ({collist}) VALUES ({placeholders})'

            # BLOB 列要转 bytes
            blob_cols = {c["name"] for c in cols
                         if (c["type"] or "").upper().startswith("BLOB")}

            values = []
            for r in rows:
                vals = []
                for n in names:
                    v = r[n]
                    if n in blob_cols and isinstance(v, str):
                        v = v.encode("utf-8", errors="replace")
                    elif n in blob_cols and isinstance(v, memoryview):
                        v = bytes(v)
                    vals.append(v)
                values.append(tuple(vals))

            pk_names = {c["name"] for c in pk}
            non_pk = [i for i, n in enumerate(names) if n not in pk_names]
            conflict = ""
            if pk_names and non_pk:
                sets = ", ".join(f'"{names[i]}" = EXCLUDED."{names[i]}"' for i in non_pk)
                conflict = f' ON CONFLICT ({", ".join(chr(34)+n+chr(34) for n in pk_names)}) DO UPDATE SET {sets}'

            try:
                await pg.executemany(insert + conflict, values)
                cnt = await pg.fetchval(f'SELECT count(*) FROM "{table}"')
                record(f"{table}: 导入数据", cnt == len(rows),
                       f"{cnt}/{len(rows)} 行")
            except Exception as exc:  # noqa: BLE001
                record(f"{table}: 导入数据", False, f"{type(exc).__name__}: {str(exc)[:120]}")
                continue

    finally:
        await pg.close()
        lite.close()

    print("\n=== 汇总 ===")
    bad = [n for n, ok, _ in RESULTS if not ok]
    print(f"{len(RESULTS)-len(bad)}/{len(RESULTS)} 通过")
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))