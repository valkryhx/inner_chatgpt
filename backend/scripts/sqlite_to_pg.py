"""SQLite -> PostgreSQL 真实数据迁移。

## 用法

    # 1. 起目标库
    docker run -d --name hlz-pg -e POSTGRES_PASSWORD=... -e POSTGRES_USER=hlz \\
        -e POSTGRES_DB=hlaudz -p 5432:5432 postgres:16-bookworm

    # 2. 先看会发生什么（不写库）
    python scripts/sqlite_to_pg.py --dsn postgresql://hlz:pw@127.0.0.1:5432/hlaudz --dry

    # 3. 真迁
    python scripts/sqlite_to_pg.py --dsn postgresql://hlz:pw@127.0.0.1:5432/hlaudz

    # 4. 校验（行数 + 抽样内容比对）
    python scripts/sqlite_to_pg.py --dsn ... --verify

## 设计要点

- **建表 DDL 不用手写**：直接读 SQLite 的 `sqlite_master`，按类型映射翻译，
  这样不会出现「脚本里的 schema 和代码里的 schema 不一致」。
- **类型映射与 pgdriver 保持一致**（INTEGER→BIGINT，BLOB→BYTEA）：
  不一致就会出现「迁移后能读、写入却溢出」这种最难查的问题。
- **自增序列要 setval**：`a2a_audit.id` 用 IDENTITY，导入时显式给了 id，
  序列还停在 1，下一条 INSERT 就撞主键。
- **一个事务**：整个迁移在一个事务里，失败全回滚，不会留半个库。
- **幂等**：`DROP TABLE IF EXISTS` + 重建，可以重复跑。
"""
from __future__ import annotations

import argparse
import asyncio
import sqlite3
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

SKIP_TABLES = {"sqlite_sequence", "__django_migrations"}

# 与 app/pgdriver.py 的 _DDL_TYPE_MAP 保持一致
TYPE_MAP = {
    "TEXT": "TEXT",
    "VARCHAR": "TEXT",
    "CHAR": "TEXT",
    "INTEGER": "BIGINT",
    "INT": "BIGINT",
    "BIGINT": "BIGINT",
    "SMALLINT": "BIGINT",
    "REAL": "DOUBLE PRECISION",
    "FLOAT": "DOUBLE PRECISION",
    "DOUBLE": "DOUBLE PRECISION",
    "BLOB": "BYTEA",
    "NUMERIC": "NUMERIC",
    "DECIMAL": "NUMERIC",
    "BOOLEAN": "BOOLEAN",
}


def map_type(sqlite_type: str) -> str:
    raw = (sqlite_type or "").upper().split("(")[0].strip()
    return TYPE_MAP.get(raw, "TEXT")


def sqlite_tables(conn: sqlite3.Connection) -> list[str]:
    names = [r[0] for r in conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table' ORDER BY name")]
    return [n for n in names if n not in SKIP_TABLES]


def table_ddl(conn: sqlite3.Connection, table: str) -> tuple[list[dict], list[str]]:
    """返回 (列定义, 主键列名)。"""
    cols = [dict(r) for r in conn.execute(f'PRAGMA table_info("{table}")')]
    pks = [c["name"] for c in cols if c["pk"]]
    return cols, pks


def build_create(table: str, cols: list[dict], pks: list[str]) -> str:
    defs = []
    single_pk = len(pks) == 1
    for c in cols:
        is_pk = c["name"] in pks
        # SQLite 的 AUTOINCREMENT 只有 a2a_audit.id 一处，用 IDENTITY 还原
        ddl_type = map_type(c["type"])
        piece = f'"{c["name"]}" {ddl_type}'
        if is_pk and single_pk and ddl_type == "BIGINT":
            piece += " GENERATED BY DEFAULT AS IDENTITY"
        if c["notnull"] or is_pk:
            piece += " NOT NULL"
        if c["dflt_value"] is not None:
            piece += f" DEFAULT {c['dflt_value']}"
        defs.append(piece)
    if single_pk:
        defs.append(f'PRIMARY KEY ("{pks[0]}")')
    elif pks:
        inner = ", ".join(f'"{p}"' for p in pks)
        defs.append(f"PRIMARY KEY ({inner})")
    return f'CREATE TABLE "{table}" (\n  ' + ",\n  ".join(defs) + "\n)"


def indexes(conn: sqlite3.Connection, table: str) -> list[str]:
    rows = conn.execute(
        "SELECT name, sql FROM sqlite_master WHERE type='index' AND tbl_name=? "
        "AND sql IS NOT NULL", (table,)).fetchall()
    out = []
    for name, sql in rows:
        # SQLite 的索引 DDL 在 PG 上语法相同；类型映射不涉及索引
        out.append(sql)
    return out


async def migrate(dsn: str, sqlite_path: Path, *, dry: bool, schema: str) -> int:
    import asyncpg

    if not sqlite_path.exists():
        print(f"SQLite 不存在：{sqlite_path}")
        return 2

    lite = sqlite3.connect(str(sqlite_path))
    lite.row_factory = sqlite3.Row

    pg = await asyncpg.connect(dsn)
    total_rows = 0
    try:
        await pg.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
        await pg.execute(f'SET search_path TO "{schema}"')

        tables = sqlite_tables(lite)
        print(f"源库：{sqlite_path}  目标：{schema}  共 {len(tables)} 张表\n")

        stmts: list[tuple[str, str]] = []      # (table, ddl)
        for t in tables:
            cols, pks = table_ddl(lite, t)
            stmts.append((t, build_create(t, cols, pks)))

        if dry:
            for t, ddl in stmts:
                print(f"--- {t} ---\n{ddl}\n")
            print("（--dry：没有写库）")
            return 0

        async with pg.transaction():
            # 幂等：先删再建（顺序无关，因为不建外键）
            for t, _ in stmts:
                await pg.execute(f'DROP TABLE IF EXISTS "{t}" CASCADE')

            for t, ddl in stmts:
                await pg.execute(ddl)

            for t in tables:
                cols, pks = table_ddl(lite, t)
                names = [c["name"] for c in cols]
                rows = lite.execute(f'SELECT * FROM "{t}"').fetchall()
                if rows:
                    blob_cols = {c["name"] for c in cols
                                 if map_type(c["type"]) == "BYTEA"}
                    values = []
                    for r in rows:
                        vals = []
                        for n in names:
                            v = r[n]
                            if n in blob_cols and v is not None:
                                if isinstance(v, str):
                                    v = v.encode("utf-8", "replace")
                                elif isinstance(v, memoryview):
                                    v = bytes(v)
                            vals.append(v)
                        values.append(tuple(vals))
                    collist = ", ".join(f'"{n}"' for n in names)
                    ph = ", ".join(f"${i+1}" for i in range(len(names)))
                    await pg.executemany(
                        f'INSERT INTO "{t}" ({collist}) VALUES ({ph})', values)
                total_rows += len(rows)
                print(f"  {t:<28} {len(rows):>7} 行")

                # 索引在数据之后建（快得多）
                for idx_sql in indexes(lite, t):
                    try:
                        await pg.execute(idx_sql)
                    except Exception as exc:  # noqa: BLE001
                        print(f"    索引失败（跳过）：{exc}")

            # 自增序列对齐：导入时显式给了 id，序列还停在 1
            for t in tables:
                cols, pks = table_ddl(lite, t)
                for pk in pks:
                    col = next(c for c in cols if c["name"] == pk)
                    if map_type(col["type"]) != "BIGINT":
                        continue
                    if not (col["pk"] and len(pks) == 1):
                        continue
                    # 只有 IDENTITY 列需要 setval
                    is_identity = await pg.fetchval(
                        "SELECT is_identity FROM information_schema.columns "
                        "WHERE table_schema = $1 AND table_name = $2 "
                        "AND column_name = $3", schema, t, pk)
                    if is_identity != "YES":
                        continue
                    await pg.execute(
                        f"SELECT setval(pg_get_serial_sequence('\"{t}\"', '{pk}'), "
                        f"COALESCE((SELECT MAX(\"{pk}\") FROM \"{t}\"), 1))"
                    )
                    print(f"  序列已对齐：{t}.{pk}")

        print(f"\n完成：{len(tables)} 张表，{total_rows:,} 行")
    finally:
        lite.close()
        await pg.close()
    return 0


async def verify(dsn: str, sqlite_path: Path, schema: str) -> int:
    """逐表比对行数 + 主键集合，确认没有漏行 / 串行。"""
    import asyncpg

    lite = sqlite3.connect(str(sqlite_path))
    lite.row_factory = sqlite3.Row
    pg = await asyncpg.connect(dsn)
    bad: list[str] = []
    try:
        await pg.execute(f'SET search_path TO "{schema}"')
        tables = sqlite_tables(lite)
        print(f"{'表':<30} {'SQLite':>8} {'PG':>8}  结果")
        print("-" * 60)
        for t in tables:
            n_lite = lite.execute(f'SELECT count(*) FROM "{t}"').fetchone()[0]
            try:
                n_pg = await pg.fetchval(f'SELECT count(*) FROM "{t}"')
            except Exception:  # noqa: BLE001
                print(f"{t:<30} {n_lite:>8} {'缺失':>8}  FAIL")
                bad.append(t)
                continue
            ok = n_lite == n_pg
            if not ok:
                bad.append(t)
            print(f"{t:<30} {n_lite:>8} {n_pg:>8}  {'ok' if ok else 'FAIL'}")

        # 抽样内容比对（行数相同也可能是错行）
        for t in ("sessions", "messages", "users"):
            if t not in tables:
                continue
            cols, pks = table_ddl(lite, t)
            if not pks:
                continue
            pk = pks[0]
            sample = lite.execute(
                f'SELECT "{pk}" FROM "{t}" ORDER BY RANDOM() LIMIT 20').fetchall()
            for (val,) in sample:
                got = await pg.fetchval(
                    f'SELECT "{pk}" FROM "{t}" WHERE "{pk}"=$1', val)
                if got != val:
                    print(f"  抽样不一致：{t}.{pk}={val!r}")
                    bad.append(t)
                    break

        print()
        if bad:
            print(f"FAIL：{len(bad)} 张表不一致 -> {bad}")
            return 1
        print(f"全部一致（{len(tables)} 张表）")
        return 0
    finally:
        lite.close()
        await pg.close()


async def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dsn", required=True)
    ap.add_argument("--sqlite", default=str(BACKEND / "data" / "app.db"))
    ap.add_argument("--schema", default="public")
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--verify", action="store_true")
    args = ap.parse_args()

    path = Path(args.sqlite)
    if args.verify:
        return await verify(args.dsn, path, args.schema)
    return await migrate(args.dsn, path, dry=args.dry, schema=args.schema)


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))